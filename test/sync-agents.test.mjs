test('model map applies per tier; opencode skips a model without provider and warns', () => {
  const dir = project();
  const r = sync(dir, ALL, ['--model-map', MAP]);
  assert.equal(r.code, 0, r.err);
  const codex = parseToml(read(dir, '.codex/agents/reviewer.toml'));
  assert.equal(codex.model, 'gpt-5');
  assert.equal(codex.model_reasoning_effort, 'high'); // from the Claude `effort: high`
  const explorer = parseToml(read(dir, '.codex/agents/explorer.toml'));
  assert.equal(explorer.model, 'gpt-5-mini');
  assert.ok(!('model_reasoning_effort' in explorer));
  assert.match(read(dir, '.gemini/agents/frontend.md'), /^model: anthropic\/claude-sonnet-4$/m);
  assert.match(read(dir, '.github/agents/explorer.agent.md'), /^model: gpt-5-mini$/m);
  assert.match(read(dir, '.opencode/agents/frontend.md'), /^model: anthropic\/claude-sonnet-4$/m);
  assert.ok(!read(dir, '.opencode/agents/explorer.md').includes('model:'));
  assert.match(r.err, /warn: \.claude\/agents\/explorer\.md: opencode: model "gpt-5-mini" has no provider\//);
  assert.match(r.err, /reviewer\.md: opencode: model "gpt-5"/);
  assert.ok(!/frontend/.test(r.err));
  // a tier without a mapping stays unmapped
  const dir2 = project();
  sync(dir2, ALL, ['--model-map', 'deep=gpt-5']);
  assert.ok(!('model' in parseToml(read(dir2, '.codex/agents/explorer.toml'))));
});

