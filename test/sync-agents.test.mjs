// Tiny TOML subset reader: comments, `key = "basic"`, `key = '''literal'''`, `key = """multi-line basic"""`.
function parseToml(text) {
  const out = {};
  const lines = text.split('\n');
  const unescape = (s) =>
    s.replace(/\\(u[0-9a-fA-F]{4}|.)/g, (_, c) => {
      if (c[0] === 'u') return String.fromCharCode(parseInt(c.slice(1), 16));
      const m = { b: '\b', t: '\t', n: '\n', f: '\f', r: '\r', '"': '"', '\\': '\\' }[c];
      assert.ok(m !== undefined, `invalid TOML escape \\${c}`);
      return m;
    });
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!line.trim() || line.startsWith('#')) continue;
    const m = line.match(/^([A-Za-z0-9_-]+) = (.*)$/);
    assert.ok(m, `not a key/value line: ${line}`);
    const [, key, val] = m;
    assert.ok(!(key in out), `duplicate key ${key}`);
    const delim = val === "'''" ? "'''" : val === '"""' ? '"""' : null;
    if (delim) {
      const body = [];
      for (i++; i < lines.length && !(delim === "'''" ? lines[i].endsWith("'''") : /(^|[^\\])"""$/.test(lines[i])); i++) body.push(lines[i]);
      assert.ok(i < lines.length, 'unterminated multi-line string');
      body.push(lines[i].slice(0, -3));
      const raw = body.join('\n');
      out[key] = delim === "'''" ? raw : unescape(raw);
    } else {
      assert.match(val, /^"(?:[^"\\]|\\.)*"$/, `bad basic string: ${val}`);
      out[key] = unescape(val.slice(1, -1));
    }
  }
  return out;
}

test('parseFrontmatter handles scalars, quotes, lists, folded blocks and nested maps', () => {
  const fm = parseFrontmatter(
    [
      'name: a-b',
      'description: >-',
      '  first line',
      '  second line',
      '',
      '  new para',
      "title: 'it''s'",
      'tools: [Read, "Grep"]',
      'skills:',
      '- x',
      '- y # note',
      'hooks:',
      '  PreToolUse:',
      '    - a',
      'model: haiku # cheap',
    ],
  );
  assert.equal(fm.name, 'a-b');
  assert.equal(fm.description, 'first line second line\nnew para');
  assert.equal(fm.title, "it's");
  assert.deepEqual(fm.tools, ['Read', 'Grep']);
  assert.deepEqual(fm.skills, ['x', 'y']);
  assert.equal(fm.hooks, null);
  assert.equal(fm.model, 'haiku');
});

test('parseAgent normalizes tools, description and body; tierOf maps aliases', () => {
  const a = parseAgent('---\r\nname: x\r\ndescription: "A  b"\r\ntools: Read, Bash(git diff:*), Agent(w, r)\r\ndisallowedTools: Write\r\n---\r\n\r\nBody\r\n', 'x');
  assert.deepEqual(a.tools, ['Read', 'Bash', 'Agent']);
  assert.deepEqual(a.disallowed, ['Write']);
  assert.equal(a.description, 'A b');
  assert.equal(a.body, 'Body\n');
  assert.equal(parseAgent('no frontmatter', 'stem').name, 'stem');
  assert.deepEqual(['haiku', 'sonnet', 'opus', 'fable', 'claude-opus-5-5', 'inherit', ''].map(tierOf), ['fast', 'standard', 'deep', 'deep', 'deep', null, null]);
});

test('parseModelMap rejects bad tiers', () => {
  assert.deepEqual(parseModelMap('fast=a, deep=b/c').map, { fast: 'a', deep: 'b/c' });
  assert.match(parseModelMap('big=a').error, /bad --model-map/);
  assert.match(parseModelMap('fast=').error, /bad --model-map/);
});

test('tomlMultiline: literal by default, escaped basic string for ones with triple quotes', () => {
  assert.equal(tomlMultiline('a\n'), "'''\na\n'''");
  for (const body of ["x ''' y\n", 'tail"\n"', 'q """ q\\n\n', 'bell\u0007\n']) {
    const t = parseToml(`k = ${tomlMultiline(body)}\n`);
    assert.equal(t.k, body);
  }
});

