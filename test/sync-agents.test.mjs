test('a hand-written file at a target path is a conflict and stays untouched', () => {
  const dir = project();
  fs.mkdirSync(path.join(dir, '.codex/agents'), { recursive: true });
  fs.writeFileSync(path.join(dir, '.codex/agents/explorer.toml'), 'name = "mine"\n');
  const r = sync(dir, 'codex');
  assert.equal(r.code, 1);
  assert.match(r.out, /conflict\s+codex\s+\.codex\/agents\/explorer\.toml \(exists without the generated marker/);
  assert.equal(read(dir, '.codex/agents/explorer.toml'), 'name = "mine"\n');
  assert.ok(exists(dir, '.codex/agents/reviewer.toml')); // others still written
});

test('stale generated files are removed; unmarked ones are not', () => {
  const dir = project();
  sync(dir);
  fs.writeFileSync(path.join(dir, '.opencode/agents/own.md'), '---\ndescription: mine\n---\nhi\n');
  fs.rmSync(path.join(dir, '.claude/agents/reviewer.md'));
  const check = sync(dir, ALL, ['--check']);
  assert.equal(check.code, 1);
  assert.match(check.out, /remove\s+codex\s+\.codex\/agents\/reviewer\.toml/);
  assert.ok(exists(dir, '.codex/agents/reviewer.toml'));
  assert.equal(sync(dir).code, 0);
  for (const f of ['.codex/agents/reviewer.toml', '.gemini/agents/reviewer.md', '.opencode/agents/reviewer.md', '.github/agents/reviewer.agent.md']) {
    assert.ok(!exists(dir, f), f);
  }
  assert.ok(exists(dir, '.opencode/agents/own.md'));
  assert.ok(exists(dir, '.codex/agents/explorer.toml'));
});

